create table if not exists public.page_views (
  id         bigint generated by default as identity primary key,
  path       text not null check (char_length(path) between 1 and 160),
  visitor    text not null check (char_length(visitor) between 1 and 64),
  viewed_on  date not null default current_date,
  created_at timestamptz not null default now()
);

create index if not exists page_views_day_idx on public.page_views (viewed_on);
create index if not exists page_views_visitor_idx on public.page_views (visitor);
create index if not exists page_views_path_idx on public.page_views (path);

alter table public.page_views enable row level security;

-- Solo los administradores pueden leer los datos.
drop policy if exists "page_views_select_admin" on public.page_views;
create policy "page_views_select_admin"
  on public.page_views for select
  to authenticated
  using (public.is_admin());

-- Registrar una visita (público, sin datos personales).
create or replace function public.log_page_view(p_path text, p_visitor text)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_path text;
  v_visitor text;
begin
  v_path := left(coalesce(nullif(btrim(p_path), ''), '/'), 160);
  v_visitor := left(coalesce(nullif(btrim(p_visitor), ''), 'anonimo'), 64);

  -- Evita duplicados por recargas o navegación rápida.
  if exists (
    select 1 from public.page_views
     where path = v_path and visitor = v_visitor
       and created_at > now() - interval '30 seconds'
  ) then
    return;
  end if;

  insert into public.page_views (path, visitor) values (v_path, v_visitor);
end;
$$;

revoke all on function public.log_page_view(text, text) from public;
grant execute on function public.log_page_view(text, text) to anon, authenticated;

-- Resumen para el panel de administración.
create or replace function public.admin_analytics()
returns json
language sql
stable
security definer
set search_path = public
as $$
  select case when not public.is_admin() then null::json else json_build_object(
    'total',         (select count(*) from public.page_views),
    'views_today',   (select count(*) from public.page_views where viewed_on = current_date),
    'views_7',       (select count(*) from public.page_views where created_at >= now() - interval '7 days'),
    'views_30',      (select count(*) from public.page_views where created_at >= now() - interval '30 days'),
    'visitors_today',(select count(distinct visitor) from public.page_views where viewed_on = current_date),
    'visitors_7',    (select count(distinct visitor) from public.page_views where created_at >= now() - interval '7 days'),
    'visitors_30',   (select count(distinct visitor) from public.page_views where created_at >= now() - interval '30 days'),
    'users',         (select count(*) from public.profiles),
    'daily', (
      select coalesce(json_agg(row_to_json(d) order by d.day), '[]'::json)
        from (
          select viewed_on as day, count(*) as views, count(distinct visitor) as visitors
            from public.page_views
           where viewed_on >= current_date - 13
           group by viewed_on
        ) d
    ),
    'top', (
      select coalesce(json_agg(row_to_json(t) order by t.views desc), '[]'::json)
        from (
          select path, count(*) as views
            from public.page_views
           where created_at >= now() - interval '7 days'
           group by path
           order by count(*) desc
           limit 10
        ) t
    )
  ) end;
$$;

revoke all on function public.admin_analytics() from public;
grant execute on function public.admin_analytics() to authenticated;
