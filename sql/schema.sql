create table if not exists public.profiles (
  id          uuid primary key references auth.users (id) on delete cascade,
  email       text,
  display_name text,
  role        text not null default 'user' check (role in ('user', 'admin')),
  blocks      text[] not null default array['comun', 'fem', 'mi'] check (blocks <@ array['comun', 'fem', 'mi']::text[]),
  created_at  timestamptz not null default now()
);

alter table public.profiles enable row level security;

-- ¿El usuario actual es administrador?
-- SECURITY DEFINER para poder consultar profiles sin recursión en las políticas.
create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.profiles
    where id = auth.uid() and role = 'admin'
  );
$$;

revoke all on function public.is_admin() from public;
grant execute on function public.is_admin() to anon, authenticated;

drop policy if exists "profiles_select_own_or_admin" on public.profiles;
create policy "profiles_select_own_or_admin"
  on public.profiles for select
  to authenticated
  using (id = auth.uid() or public.is_admin());

drop policy if exists "profiles_update_admin" on public.profiles;
create policy "profiles_update_admin"
  on public.profiles for update
  to authenticated
  using (public.is_admin())
  with check (public.is_admin());

-- Crea el perfil automáticamente al registrarse.
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_blocks text[];
begin
  v_blocks := array(
    select distinct b
    from jsonb_array_elements_text(coalesce(new.raw_user_meta_data -> 'blocks', '[]'::jsonb)) as t(b)
    where b in ('comun', 'fem', 'mi')
    order by b
  );

  insert into public.profiles (id, email, display_name, role, blocks)
  values (
    new.id,
    new.email,
    coalesce(
      nullif(new.raw_user_meta_data ->> 'display_name', ''),
      split_part(coalesce(new.email, ''), '@', 1)
    ),
    'user',
    coalesce(v_blocks, '{}'::text[])
  )
  on conflict (id) do update set email = excluded.email;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

-- Backfill: crea perfiles para usuarios que ya existieran antes de este SQL.
insert into public.profiles (id, email, display_name, role)
select
  u.id,
  u.email,
  coalesce(nullif(u.raw_user_meta_data ->> 'display_name', ''), split_part(coalesce(u.email, ''), '@', 1)),
  'user'
from auth.users u
on conflict (id) do nothing;

