-- Cambiar los bloques de la propia cuenta (solo esa columna, sin tocar el rol).
create or replace function public.set_my_blocks(p_blocks text[])
returns text[]
language plpgsql
security definer
set search_path = public
as $$
declare
  v_blocks text[];
begin
  if auth.uid() is null then
    raise exception 'Debes iniciar sesión';
  end if;

  v_blocks := array(
    select distinct b
    from unnest(coalesce(p_blocks, '{}'::text[])) as t(b)
    where b in ('comun', 'fem', 'mi')
    order by b
  );

  update public.profiles
     set blocks = v_blocks
   where id = auth.uid();

  return v_blocks;
end;
$$;

revoke all on function public.set_my_blocks(text[]) from public;
grant execute on function public.set_my_blocks(text[]) to authenticated;

-- Permisos de tabla (las filas siguen limitadas por RLS).
grant select, update on public.profiles to authenticated;
grant select, insert, update, delete on public.confirmations to authenticated;
grant usage, select on sequence public.confirmations_id_seq to authenticated;

create or replace function public.touch_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists confirmations_touch_updated_at on public.confirmations;
create trigger confirmations_touch_updated_at
  before update on public.confirmations
  for each row execute function public.touch_updated_at();

-- Resumen público (solo agregados) para pintar el estado en cada pregunta.
-- No expone emails ni filas individuales.
create or replace function public.question_confirmation_stats()
returns table (
  question_uid text,
  confirms     integer,
  disputes     integer,
  last_at      timestamptz
)
language sql
stable
security definer
set search_path = public
as $$
  select
    c.question_uid,
    count(*) filter (where c.is_correct)::int as confirms,
    count(*) filter (where not c.is_correct)::int as disputes,
    max(c.created_at) as last_at
  from public.confirmations c
  group by c.question_uid;
$$;

revoke all on function public.question_confirmation_stats() from public;
grant execute on function public.question_confirmation_stats() to anon, authenticated;

