-- ---------------------------------------------------------------------
-- 1. Perfiles
-- ---------------------------------------------------------------------
create table if not exists public.profiles (
  id          uuid primary key references auth.users (id) on delete cascade,
  email       text,
  display_name text,
  role        text not null default 'user' check (role in ('user', 'admin')),
  created_at  timestamptz not null default now()
);

alter table public.profiles enable row level security;

-- ¿El usuario actual es administrador?
-- SECURITY DEFINER para poder consultar profiles sin recursión en las políticas.
create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.profiles
    where id = auth.uid() and role = 'admin'
  );
$$;

revoke all on function public.is_admin() from public;
grant execute on function public.is_admin() to anon, authenticated;

drop policy if exists "profiles_select_own_or_admin" on public.profiles;
create policy "profiles_select_own_or_admin"
  on public.profiles for select
  to authenticated
  using (id = auth.uid() or public.is_admin());

drop policy if exists "profiles_update_admin" on public.profiles;
create policy "profiles_update_admin"
  on public.profiles for update
  to authenticated
  using (public.is_admin())
  with check (public.is_admin());

-- Crea el perfil automáticamente al registrarse.
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, email, display_name, role)
  values (
    new.id,
    new.email,
    coalesce(
      nullif(new.raw_user_meta_data ->> 'display_name', ''),
      split_part(coalesce(new.email, ''), '@', 1)
    ),
    'user'
  )
  on conflict (id) do update set email = excluded.email;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

-- Backfill: crea perfiles para usuarios que ya existieran antes de este SQL.
insert into public.profiles (id, email, display_name, role)
select
  u.id,
  u.email,
  coalesce(nullif(u.raw_user_meta_data ->> 'display_name', ''), split_part(coalesce(u.email, ''), '@', 1)),
  'user'
from auth.users u
on conflict (id) do nothing;

-- ---------------------------------------------------------------------
-- 2. Confirmaciones de respuestas
-- ---------------------------------------------------------------------
create table if not exists public.confirmations (
  id               bigint generated by default as identity primary key,
  question_uid     text not null check (question_uid ~ '^(comun|fem)-[0-9]{1,3}$'),
  user_id          uuid not null references public.profiles (id) on delete cascade,
  is_correct       boolean not null default true,
  suggested_answer text check (suggested_answer is null or suggested_answer in ('a', 'b', 'c', 'd')),
  comment          text check (comment is null or char_length(comment) <= 1000),
  created_at       timestamptz not null default now(),
  updated_at       timestamptz not null default now(),
  unique (question_uid, user_id)
);

create index if not exists confirmations_question_idx on public.confirmations (question_uid);
create index if not exists confirmations_user_idx on public.confirmations (user_id);

alter table public.confirmations enable row level security;

drop policy if exists "confirmations_select_own_or_admin" on public.confirmations;
create policy "confirmations_select_own_or_admin"
  on public.confirmations for select
  to authenticated
  using (user_id = auth.uid() or public.is_admin());

drop policy if exists "confirmations_insert_own" on public.confirmations;
create policy "confirmations_insert_own"
  on public.confirmations for insert
  to authenticated
  with check (user_id = auth.uid());

drop policy if exists "confirmations_update_own" on public.confirmations;
create policy "confirmations_update_own"
  on public.confirmations for update
  to authenticated
  using (user_id = auth.uid())
  with check (user_id = auth.uid());

drop policy if exists "confirmations_delete_own_or_admin" on public.confirmations;
create policy "confirmations_delete_own_or_admin"
  on public.confirmations for delete
  to authenticated
  using (user_id = auth.uid() or public.is_admin());

-- Permisos de tabla (las filas siguen limitadas por RLS).
grant select, update on public.profiles to authenticated;
grant select, insert, update, delete on public.confirmations to authenticated;
grant usage, select on sequence public.confirmations_id_seq to authenticated;

create or replace function public.touch_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists confirmations_touch_updated_at on public.confirmations;
create trigger confirmations_touch_updated_at
  before update on public.confirmations
  for each row execute function public.touch_updated_at();

-- Resumen público (solo agregados) para pintar el estado en cada pregunta.
-- No expone emails ni filas individuales.
create or replace function public.question_confirmation_stats()
returns table (
  question_uid text,
  confirms     integer,
  disputes     integer,
  last_at      timestamptz,
  confirmers   text[]
)
language sql
stable
security definer
set search_path = public
as $$
  select
    c.question_uid,
    count(*) filter (where c.is_correct)::int as confirms,
    count(*) filter (where not c.is_correct)::int as disputes,
    max(c.created_at) as last_at,
    (array_agg(
       coalesce(nullif(p.display_name, ''), split_part(coalesce(p.email, ''), '@', 1), 'Usuario')
       order by c.created_at desc
     ) filter (where c.is_correct))[1:5] as confirmers
  from public.confirmations c
  left join public.profiles p on p.id = c.user_id
  group by c.question_uid;
$$;

revoke all on function public.question_confirmation_stats() from public;
grant execute on function public.question_confirmation_stats() to anon, authenticated;

-- ---------------------------------------------------------------------
-- 3. Progreso de respuestas (sincroniza el avance entre dispositivos)
-- ---------------------------------------------------------------------
create table if not exists public.attempts (
  user_id       uuid not null references public.profiles (id) on delete cascade,
  question_uid  text not null check (question_uid ~ '^(comun|fem)-[0-9]{1,3}$'),
  pick          text not null check (pick in ('a', 'b', 'c', 'd')),
  is_correct    boolean not null,
  answered_at   timestamptz not null default now(),
  primary key (user_id, question_uid)
);

alter table public.attempts enable row level security;

drop policy if exists "attempts_select_own" on public.attempts;
create policy "attempts_select_own"
  on public.attempts for select
  to authenticated
  using (user_id = auth.uid());

drop policy if exists "attempts_insert_own" on public.attempts;
create policy "attempts_insert_own"
  on public.attempts for insert
  to authenticated
  with check (user_id = auth.uid());

drop policy if exists "attempts_update_own" on public.attempts;
create policy "attempts_update_own"
  on public.attempts for update
  to authenticated
  using (user_id = auth.uid())
  with check (user_id = auth.uid());

drop policy if exists "attempts_delete_own" on public.attempts;
create policy "attempts_delete_own"
  on public.attempts for delete
  to authenticated
  using (user_id = auth.uid());

grant select, insert, update, delete on public.attempts to authenticated;

