-- =====================================================================
--  Migración: intentos agrupados
-- ---------------------------------------------------------------------
--  Pasa del modelo antiguo (una fila por pregunta en `attempts`) al
--  modelo nuevo:
--
--    attempt_groups   cada intento (puede quedar incompleto)
--    attempts         respuestas de un intento
--
--  Es idempotente: si `attempts` ya tiene `group_id`, no vuelve a migrar.
--  Se puede ejecutar en el SQL Editor de Supabase.
-- =====================================================================

do $$
begin
  if exists (
    select 1 from information_schema.columns
    where table_schema = 'public' and table_name = 'attempts' and column_name = 'group_id'
  ) then
    raise notice 'La migración ya está aplicada.';
    return;
  end if;

  if exists (
    select 1 from information_schema.tables
    where table_schema = 'public' and table_name = 'attempts'
  ) then
    alter table public.attempts rename to attempts_legacy;
  end if;

  create table if not exists public.attempt_groups (
    id          uuid primary key default gen_random_uuid(),
    user_id     uuid not null references public.profiles (id) on delete cascade,
    battery     text not null check (battery in ('comun', 'fem')),
    name        text not null default 'Intento',
    created_at  timestamptz not null default now(),
    updated_at  timestamptz not null default now()
  );

  create table if not exists public.attempts (
    id            bigint generated by default as identity primary key,
    group_id      uuid not null references public.attempt_groups (id) on delete cascade,
    user_id       uuid not null references public.profiles (id) on delete cascade,
    question_uid  text not null check (question_uid ~ '^(comun|fem)-[0-9]{1,3}$'),
    pick          text not null check (pick in ('a', 'b', 'c', 'd')),
    is_correct    boolean not null,
    answered_at   timestamptz not null default now(),
    unique (group_id, question_uid)
  );

  if exists (
    select 1 from information_schema.tables
    where table_schema = 'public' and table_name = 'attempts_legacy'
  ) then
    insert into public.attempt_groups (user_id, battery, name, created_at)
    select user_id, split_part(question_uid, '-', 1), 'Progreso anterior', min(answered_at)
    from public.attempts_legacy
    group by user_id, split_part(question_uid, '-', 1);

    insert into public.attempts (group_id, user_id, question_uid, pick, is_correct, answered_at)
    select g.id, l.user_id, l.question_uid, l.pick, l.is_correct, l.answered_at
    from public.attempts_legacy l
    join public.attempt_groups g
      on g.user_id = l.user_id
     and g.battery = split_part(l.question_uid, '-', 1)
     and g.name = 'Progreso anterior';

    drop table public.attempts_legacy;
  end if;
end;
$$;

create index if not exists attempt_groups_user_idx on public.attempt_groups (user_id, battery, created_at desc);
create index if not exists attempts_group_idx on public.attempts (group_id);
create index if not exists attempts_user_idx on public.attempts (user_id);
create index if not exists attempts_question_idx on public.attempts (question_uid);
create index if not exists attempts_wrong_idx on public.attempts (question_uid) where not is_correct;

alter table public.attempt_groups enable row level security;
alter table public.attempts enable row level security;

drop policy if exists "attempt_groups_select_own" on public.attempt_groups;
create policy "attempt_groups_select_own"
  on public.attempt_groups for select
  to authenticated
  using (user_id = auth.uid());

drop policy if exists "attempt_groups_insert_own" on public.attempt_groups;
create policy "attempt_groups_insert_own"
  on public.attempt_groups for insert
  to authenticated
  with check (user_id = auth.uid());

drop policy if exists "attempt_groups_update_own" on public.attempt_groups;
create policy "attempt_groups_update_own"
  on public.attempt_groups for update
  to authenticated
  using (user_id = auth.uid())
  with check (user_id = auth.uid());

drop policy if exists "attempt_groups_delete_own" on public.attempt_groups;
create policy "attempt_groups_delete_own"
  on public.attempt_groups for delete
  to authenticated
  using (user_id = auth.uid());

drop policy if exists "attempts_select_own" on public.attempts;
create policy "attempts_select_own"
  on public.attempts for select
  to authenticated
  using (user_id = auth.uid());

drop policy if exists "attempts_insert_own" on public.attempts;
create policy "attempts_insert_own"
  on public.attempts for insert
  to authenticated
  with check (
    user_id = auth.uid()
    and exists (
      select 1 from public.attempt_groups g
      where g.id = group_id and g.user_id = auth.uid()
    )
  );

drop policy if exists "attempts_update_own" on public.attempts;
create policy "attempts_update_own"
  on public.attempts for update
  to authenticated
  using (user_id = auth.uid())
  with check (
    user_id = auth.uid()
    and exists (
      select 1 from public.attempt_groups g
      where g.id = group_id and g.user_id = auth.uid()
    )
  );

drop policy if exists "attempts_delete_own" on public.attempts;
create policy "attempts_delete_own"
  on public.attempts for delete
  to authenticated
  using (user_id = auth.uid());

grant select, insert, update, delete on public.attempt_groups to authenticated;
grant select, insert, update, delete on public.attempts to authenticated;
grant usage, select on sequence public.attempts_id_seq to authenticated;

create or replace function public.touch_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists attempt_groups_touch_updated_at on public.attempt_groups;
create trigger attempt_groups_touch_updated_at
  before update on public.attempt_groups
  for each row execute function public.touch_updated_at();

create or replace function public.question_failure_stats()
returns table (
  question_uid  text,
  attempts      integer,
  failures      integer,
  failure_rate  numeric,
  last_at       timestamptz
)
language sql
stable
security definer
set search_path = public
as $$
  select
    a.question_uid,
    count(*)::int as attempts,
    count(*) filter (where not a.is_correct)::int as failures,
    round(100.0 * count(*) filter (where not a.is_correct) / nullif(count(*), 0), 1) as failure_rate,
    max(a.answered_at) as last_at
  from public.attempts a
  group by a.question_uid;
$$;

revoke all on function public.question_failure_stats() from public;
grant execute on function public.question_failure_stats() to anon, authenticated;
