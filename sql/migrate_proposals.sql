-- =====================================================================
--  Propuestas de mejora y avisos de fallos
-- ---------------------------------------------------------------------
--  Ejecuta este archivo completo en:
--    Supabase Dashboard > SQL Editor > New query > Run
--
--  Crea la tabla public.proposals, sus índices, permisos y políticas RLS:
--    - Cada usuario puede crear propuestas y ver las suyas.
--    - Un administrador puede ver todas y responderlas.
--    - El autor (o un administrador) puede eliminar una propuesta.
-- =====================================================================

create table if not exists public.proposals (
  id          bigint generated by default as identity primary key,
  user_id     uuid not null references public.profiles (id) on delete cascade,
  kind        text not null default 'mejora' check (kind in ('mejora', 'fallo')),
  title       text not null check (char_length(title) between 1 and 120),
  body        text not null check (char_length(body) between 1 and 2000),
  context     text check (context is null or char_length(context) <= 200),
  status      text not null default 'pending' check (status in ('pending', 'answered')),
  admin_reply text check (admin_reply is null or char_length(admin_reply) <= 2000),
  replied_by  uuid references public.profiles (id) on delete set null,
  replied_at  timestamptz,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);

create index if not exists proposals_user_idx on public.proposals (user_id, created_at desc);
create index if not exists proposals_status_idx on public.proposals (status, created_at desc);

alter table public.proposals enable row level security;

drop policy if exists "proposals_select_own_or_admin" on public.proposals;
create policy "proposals_select_own_or_admin"
  on public.proposals for select
  to authenticated
  using (user_id = auth.uid() or public.is_admin());

-- Al crear una propuesta el usuario no puede falsear el estado ni la respuesta.
drop policy if exists "proposals_insert_own" on public.proposals;
create policy "proposals_insert_own"
  on public.proposals for insert
  to authenticated
  with check (
    user_id = auth.uid()
    and status = 'pending'
    and admin_reply is null
    and replied_by is null
    and replied_at is null
  );

-- Solo los administradores cambian el estado y la respuesta.
drop policy if exists "proposals_update_admin" on public.proposals;
create policy "proposals_update_admin"
  on public.proposals for update
  to authenticated
  using (public.is_admin())
  with check (public.is_admin());

drop policy if exists "proposals_delete_own_or_admin" on public.proposals;
create policy "proposals_delete_own_or_admin"
  on public.proposals for delete
  to authenticated
  using (user_id = auth.uid() or public.is_admin());

grant select, insert, delete on public.proposals to authenticated;
grant update on public.proposals to authenticated;
grant usage, select on sequence public.proposals_id_seq to authenticated;

drop trigger if exists proposals_touch_updated_at on public.proposals;
create trigger proposals_touch_updated_at
  before update on public.proposals
  for each row execute function public.touch_updated_at();
